"""Cross-post queue for TikTok and Instagram Reels (Nov 3, 2026; owner: "start crossposting process"). Zero Claude credits.

  python Tools/crosspost.py            -> writes Research Notes/Crosspost Queue.md and prints a summary

For every Short uploaded to YouTube (Research Notes/Scheduled Uploads.csv) whose file still exists on the PC, it lists: the file to post
(the same DRAFT that went to YouTube: under 60 s, 1080x1920, fine for both apps), a TikTok caption and an Instagram caption built from the
card's title and pinned-comment question, 3-5 hashtags per channel, and when to post it (TikTok/IG copy goes up after the YouTube
publish time, so YouTube gets the first day). Rows already marked done in the queue file keep their [x].
Posting itself is the owner's (or Metricool's, once TikTok and Instagram are connected there; the post goes for review first).
"""
import csv, datetime, os, re
from zoneinfo import ZoneInfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = os.path.join(ROOT, "Research Notes", "Scheduled Uploads.csv")
OUT = os.path.join(ROOT, "Research Notes", "Crosspost Queue.md")
ET = ZoneInfo("America/New_York")
CHTAG = {"nba": "#nba", "fc": "#football"}  # one channel tag; the rest come from the Short's own tags (Growth Study, Nov 3)
HANDLE = {"nba": "MetaSports (NBA)", "fc": "MetaSports FC"}


def card_field(card, name):
    if not os.path.exists(card):
        return ""
    m = re.search(rf"\*\*{name}(?: \([^)]*\))?:\*\*\s*([^\n*]+)", open(card, encoding="utf-8-sig").read(), re.I)
    return m.group(1).strip() if m else ""


def hashtags(card, ch):
    """3 hashtags from the card's own tags (most specific first in our cards), plus the channel tag. Instagram: hashtags barely
    matter for reach (Mosseri), so keep them few; TikTok search reads them with the caption."""
    out = []
    for t in card_field(card, "Tags").split(","):
        h = "#" + re.sub(r"[^a-z0-9]", "", t.lower())
        if len(h) > 3 and h not in out and h != CHTAG[ch]:
            out.append(h)
        if len(out) == 3:
            break
    return " ".join(out + [CHTAG[ch]])


def emoji_free(s):
    return re.sub(r"[^\w\s'.,!?%$&:;()\-\"]", "", s).strip()


def main():
    done = set()
    if os.path.exists(OUT):
        done = set(re.findall(r"- \[x\] .*?`(\w[\w-]{10})`", open(OUT, encoding="utf-8").read()))
    rows, now = [], datetime.datetime.now(ET)
    for r in csv.DictReader(open(LOG, encoding="utf-8")):
        f = (r.get("file") or "").strip()
        path = os.path.join(ROOT, f.replace("\\", os.sep)) if f else ""
        if not f or not os.path.exists(path):
            continue
        card = os.path.join(os.path.dirname(path), "UPLOAD.md")
        title = emoji_free(r.get("title") or card_field(card, "Title"))
        question = card_field(card, "Pinned comment")
        ch = r["channel"]
        yt = datetime.datetime.strptime(r["publish_et"][:16], "%Y-%m-%d %H:%M").replace(tzinfo=ET)
        post_at = yt + datetime.timedelta(hours=3)
        rows.append((post_at, ch, r["video_id"], title, question, os.path.relpath(path, ROOT), hashtags(card, ch)))
    rows.sort()
    lines = ["# Cross-post queue: TikTok + Instagram Reels (generated by `python Tools/crosspost.py`; tick [x] when posted)", "",
             "Post the SAME file as YouTube. TikTok: add a trending sound only at very low volume, or none (our voice carries it). "
             "Instagram: post as a Reel, share to the feed. Pin the question as the first comment on both. Never post before the YouTube time.", ""]
    for post_at, ch, vid, title, q, rel, tags in rows:
        mark = "x" if vid in done else " "
        cap = title + ("" if re.search(r"[.!?]$", title) else ".") + (" " + q if q else "")
        lines += [f"- [{mark}] **{post_at:%a %b %d, %I:%M %p} ET** · {HANDLE[ch]} · `{vid}` · {title}",
                  f"  - File: `{rel}`",
                  f"  - TikTok caption: {cap} {tags}",
                  f"  - Instagram caption: {cap}\n\n    {tags}",
                  ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    todo = [x for x in rows if x[2] not in done]
    print(f"{len(rows)} Shorts with a file on the PC; {len(todo)} not yet cross-posted -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
